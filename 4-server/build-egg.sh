#!/usr/bin/env bash
# Renders the Pelican egg (PLCN_v3 YAML) from env/server.env, so the egg defaults and the
# local boot test share one source of truth. Secrets are declared with empty defaults and
# are set per server through the Pelican API (SOPS), never committed. Toggles are CFG_* switches
# that are not secret and not in server.env; they are editable in the panel and default to off.
# Usage: 4-server/build-egg.sh > 4-server/egg.yaml
set -euo pipefail

here="$(cd "$(dirname "$0")" && pwd)"
env_file="$here/env/server.env"
image="${ITZG_IMAGE:-itzg/minecraft-server:java25}"

# Variables the panel should show to admins (the rest are hidden). Secrets are listed last.
secrets=(CFG_DISCORD_BOT_TOKEN)
# Non-secret CFG_* switches as NAME=default. DiscordSRV linking.yml needs a bot, so it is off until one is set.
toggles=(CFG_DISCORDSRV_REQUIRE_LINK=false)

emit_var() { # sort name env default viewable editable
  printf '  -\n    sort: %s\n    name: %s\n    description: %s\n    env_variable: %s\n    default_value: %s\n    user_viewable: %s\n    user_editable: %s\n    rules:\n      - %s\n      - string\n' \
    "$1" "'$2'" "'Managed in Git (4-server/env/server.env).'" "$3" "'$4'" "$5" "$6" "$7"
}

cat <<YAML
_comment: 'GENERATED by 4-server/build-egg.sh from env/server.env. Do not edit.'
meta:
  version: PLCN_v3
  update_url: null
name: 'Heldengilde Paper (itzg)'
author: devops@heldengilde.nl
uuid: 8f9d4c2a-6b3e-4f1a-9c8d-2e5f7a1b3c4d
description: 'Paper on itzg/minecraft-server. Requires Pelican Mounts at /data, /gitops (ro), /plugins (ro) and /config (ro). See ADR 0002.'
tags:
  - minecraft
  - itzg
features:
  - eula
docker_images:
  'itzg Java 25': '${image}'
file_denylist: {}
startup_commands:
  Default: 'ignored by Wings: the image ENTRYPOINT (/start) runs'
config:
  files: {}
  startup:
    done: ')! For help, type '
  logs: {}
  stop: stop
scripts:
  installation:
    script: |-
      #!/bin/ash
      mkdir -p /mnt/server
      echo "nothing to install; itzg downloads the server and plugins at start"
    container: 'alpine:3.20'
    entrypoint: ash
variables:
YAML

n=1
while IFS= read -r line; do
  case "$line" in ''|'#'*) continue ;; esac
  key=${line%%=*}; val=${line#*=}
  case "$key" in VERSION|MEMORY|MAX_PLAYERS|VIEW_DISTANCE|SIMULATION_DISTANCE|MOTD|DIFFICULTY|PVP) view=true ;; *) view=false ;; esac
  emit_var "$n" "$key" "$key" "$val" "$view" false required
  n=$((n + 1))
done < "$env_file"

for t in "${toggles[@]}"; do
  emit_var "$n" "${t%%=*}" "${t%%=*}" "${t#*=}" true true required
  n=$((n + 1))
done

for s in "${secrets[@]}"; do
  emit_var "$n" "$s" "$s" "" false true required
  n=$((n + 1))
done
